/// <summary>MTG: Dark Confidant (Final Fantasy), art by Immanuela Crovius.<br/>Original text: At the beginning of your upkeep, reveal the top card of your library and put that card into your hand. You lose life equal to its mana value.</summary>
public sealed class DarkConfidant : PlaneswalkerCard
{
    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new DynamicVar("Power", 1m)
    ];

    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromPower<DarkConfidantPower>(), HoverTipFactory.FromPower<BlackManaPower>()];

    public DarkConfidant() : base(1, CardType.Power, CardRarity.Rare, TargetType.Self)
    {
    }

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        await CreatureCmd.TriggerAnim(Owner.Creature, "PowerUp", Owner.Character.PowerUpAnimDelay);
        await PowerCmd.Apply<DarkConfidantPower>(choiceContext, Owner.Creature, DynamicVars["Power"].BaseValue, Owner.Creature, this);
    }

    protected override void OnUpgrade()
    {
        EnergyCost.UpgradeBy(-1);
    }
}
